import { createHash } from "node:crypto";
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import subsetFont from "subset-font";

const root = fileURLToPath(new URL("../", import.meta.url));
const ui = new Set(Array.from({ length: 95 }, (_, i) => String.fromCodePoint(i + 32)));
async function scan(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const filename = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      if (!["fonts", "node_modules", ".next"].includes(entry.name)) await scan(filename);
    } else if (/\.(ts|tsx)$/.test(entry.name)) {
      for (const char of await readFile(filename, "utf8")) ui.add(char);
    }
  }
}
for (const directory of ["app", "components", "hooks", "lib"])
  await scan(path.join(root, directory));
const story = new Set();
const dataDir = path.resolve(root, "../data");
const files = (await readdir(dataDir)).filter((name) => /^stories_.*\.json$/.test(name)).sort();
const hash = createHash("sha256");
for (const name of files) {
  const bytes = await readFile(path.join(dataDir, name));
  hash.update(name).update("\0").update(bytes).update("\0");
  for (const char of bytes.toString("utf8")) if (!ui.has(char)) story.add(char);
}
const manifest = JSON.parse(await readFile(path.join(dataDir, "manifest.json"), "utf8"));
if (manifest.version !== `sha256:${hash.digest("hex")}`) {
  throw new Error(
    "Story manifest is stale. Run python3 scripts/stories.py manifest from the repository root.",
  );
}
const source = await readFile(path.join(root, "fonts/fusion-pixel-source.woff2"));
const output = path.join(root, "app/fonts");
await mkdir(output, { recursive: true });
for (const [name, characters] of [
  ["pixel-ui", ui],
  ["pixel-stories", story],
]) {
  const font = await subsetFont(source, [...characters].sort().join(""), { targetFormat: "woff2" });
  await writeFile(path.join(output, `${name}.woff2`), font);
  console.log(`${name}: ${characters.size} characters, ${font.length} bytes`);
}
// Disjoint unicode ranges prevent both files from being downloaded for the same glyph.
const points = [...story].map((char) => char.codePointAt(0)).sort((a, b) => a - b);
const ranges = [];
for (let i = 0; i < points.length; i++) {
  const first = points[i];
  while (points[i + 1] === points[i] + 1) i++;
  const last = points[i];
  ranges.push(`U+${first.toString(16)}${last === first ? "" : `-${last.toString(16)}`}`);
}
await writeFile(
  path.join(output, "stories.css"),
  `/* Generated by prepare-assets.mjs. */\n@font-face {\n  font-family: "Biodays Story Pixel";\n  src: url("./pixel-stories.woff2") format("woff2");\n  font-display: swap;\n  unicode-range: ${ranges.join(",")};\n}\n`,
);
